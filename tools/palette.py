def fmt(x):
    s = ('%.2f' % x).rstrip('0').rstrip('.')
    return s.replace('.', ',')


def parts(color, ml):
    """ml of colour concentrate -> dict of base concentrates"""
    if color in SEC:
        return {b: ml * p / 100 for b, p in SEC[color][1].items()}
    return {color: ml}


def rows():
    out = []
    for c in ORDER:
        sec = c in SEC
        cname = SEC[c][0] if sec else BASE[c]
        levels = ['40', '30', '20', '15', '10', '5'] if c == 'INKBP' else ['40', '15', '5', '2', 'B1005', 'B1002']
        for lv in levels:
            code = c + lv
            if lv.startswith('B'):
                pct = {'B1005': 0.5, 'B1002': 0.2}[lv]
                conc = '10%% INKBP + %s%% %s' % (fmt(pct), c)
                comp = {'INKBP': 100.0}
                comp.update(parts(c, pct * 10))
            else:
                pct = float(lv)
                conc = '%s%% %s' % (lv, c)
                comp = parts(c, pct * 10)
            total = sum(comp.values())
            comp_s = ' + '.join('%s %s' % (b, fmt(v)) for b, v in comp.items())
            comp_s += '; основа %s' % fmt(1000 - total)
            tone = WHITE_TONE[lv] if c == 'INKBP' else TONE[lv]
            names = N[c][lv]
